#include <iostream>

#include "CMemory.h"
#include "CPU.h"
#include "Debug.h"

#include <vector>

std::vector<uint8_t> makeProgram() {
    return {
        // Input three values and store in memory
        INP,   0x00, 0xF0, 0x00, 0x00,   // memory[0xF000] = input
        INP,   0x00, 0xF2, 0x00, 0x00,   // memory[0xF002] = input
        INP,   0x00, 0xF4, 0x00, 0x00,   // memory[0xF004] = input

        // Convert ASCII to numbers (subtract 48 = '0')
        LDMEM, 0x00, 0x00, 0x00, 0xF0,   // A = memory[0xF000]
        LD,    0x01, 0x00, 0x30, 0x00,   // B = 48
        SUB,   0x00, 0x00, 0x01, 0x00,   // A = A - B
        STORE, 0x00, 0x00, 0x00, 0xF0,   // memory[0xF000] = A

        LDMEM, 0x00, 0x00, 0x00, 0xF2,   // A = memory[0xF002]
        LD,    0x01, 0x00, 0x30, 0x00,   // B = 48
        SUB,   0x00, 0x00, 0x01, 0x00,   // A = A - B
        STORE, 0x00, 0x00, 0x00, 0xF2,   // memory[0xF002] = A

        LDMEM, 0x00, 0x00, 0x00, 0xF4,   // A = memory[0xF004]
        LD,    0x01, 0x00, 0x30, 0x00,   // B = 48
        SUB,   0x00, 0x00, 0x01, 0x00,   // A = A - B
        STORE, 0x00, 0x00, 0x00, 0xF4,   // memory[0xF004] = A

        // Add all three together
        LDMEM, 0x00, 0x00, 0x00, 0xF0,   // A = first value
        LDMEM, 0x01, 0x00, 0x00, 0xF2,   // B = second value
        ADD,   0x00, 0x00, 0x01, 0x00,   // A = A + B
        LDMEM, 0x01, 0x00, 0x00, 0xF4,   // B = third value
        ADD,   0x00, 0x00, 0x01, 0x00,   // A = A + B

        // Convert back to ASCII (add 48) and output
        LD,    0x01, 0x00, 0x30, 0x00,   // B = 48
        ADD,   0x00, 0x00, 0x01, 0x00,   // A = A + 48
        STORE, 0x00, 0x00, 0x06, 0xF0,   // memory[0xF006] = ASCII result
        OUT,   0x06, 0xF0, 0x00, 0x00,   // print memory[0xF006]

        HLT,   0x00, 0x00, 0x00, 0x00,
    };
}

int main() {
	Memory* memory = new Memory();

	MemoryPrinter printer(*memory);
	CPU cpu(*memory);

	auto program = makeProgram();
	memory->LoadProgram(program.data(), program.size(), 0);

	printer.StartSession();

	while (!cpu.halted) {
		cpu.Step();
		printer.WriteDeltaMemory();
	}

	printer.EndSession();

	delete memory;
}